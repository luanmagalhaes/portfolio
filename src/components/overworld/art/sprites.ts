import { paletteChars, type PaletteChar } from "@/components/overworld/art/palette";

export type SpriteRows = string[];

export function rowsOf(block: string): SpriteRows {
  return block.split("\n").filter((line) => line.trim().length > 0).map((line) => line.trim());
}

export function mirrorRows(rows: SpriteRows): SpriteRows {
  return rows.map((row) => row + row.split("").reverse().join(""));
}

export function flipRows(rows: SpriteRows): SpriteRows {
  return rows.map((row) => row.split("").reverse().join(""));
}

export function swapChars(rows: SpriteRows, swaps: Partial<Record<string, string>>): SpriteRows {
  return rows.map((row) => row.split("").map((char) => swaps[char] ?? char).join(""));
}

export function isPaletteChar(char: string): char is PaletteChar {
  return char in paletteChars;
}

